using System.Globalization;

namespace Lux3D.Core;

/// <summary>English source strings with an optional Simplified Chinese UI translation.
/// The host resolves language once at plugin load and passes it to the private child process.
/// This never changes the process culture used for parsing, protocol values or user input.</summary>
public static class LocalText
{
    public const string LanguageEnvironmentVariable = "LUX3D_UI_LANGUAGE";
    private static string _language = "en";
    public static string Language => Volatile.Read(ref _language);

    public static string ResolveLanguage(int? rhinoLanguageId, string? systemUiLanguage)
    {
        if (rhinoLanguageId is > 0 and not 127)
        {
            try
            {
                CultureInfo rhino = CultureInfo.GetCultureInfo(rhinoLanguageId.Value);
                if (!string.IsNullOrEmpty(rhino.Name)) return Select(rhino);
            }
            catch (CultureNotFoundException) { }
        }
        try { return Select(CultureInfo.GetCultureInfo(systemUiLanguage ?? "")); }
        catch (CultureNotFoundException) { return "en"; }
    }
    private static string Select(CultureInfo culture) => culture.TwoLetterISOLanguageName.Equals("zh", StringComparison.OrdinalIgnoreCase) ? "zh-Hans" : "en";
    public static void Configure(int? rhinoLanguageId, string? systemUiLanguage) =>
        Volatile.Write(ref _language, ResolveLanguage(rhinoLanguageId, systemUiLanguage));
    public static string Get(string english) => Get(english, Language);
    public static string Get(string english, string language) =>
        language == "zh-Hans" && Chinese.TryGetValue(english, out string? value) ? value : english;
    public static string Format(string english, params object?[] arguments) =>
        string.Format(CultureInfo.CurrentCulture, Get(english), arguments);

    /// <summary>Translate only recognized complete persisted diagnostic messages. Unknown provider text is preserved.</summary>
    public static string? RecordedMessage(string? message) => RecordedMessage(message, Language);
    internal static string? RecordedMessage(string? message, string language)
    {
        if (message is null) return null;
        if (Chinese.ContainsKey(message)) return Get(message, language);
        foreach (var pair in Chinese)
            if (message == pair.Value) return Get(pair.Key, language);
        return message;
    }

